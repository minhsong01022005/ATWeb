-- Run as HR_APP in FREEPDB1 to remove only the department VPD policies.
-- The application context package can remain installed without filtering rows.
BEGIN
  DBMS_RLS.DROP_POLICY('HR_APP', 'EMPLOYEES', 'HR_EMPLOYEE_DEPT_VPD');
EXCEPTION
  WHEN OTHERS THEN
    IF SQLCODE != -28102 THEN RAISE; END IF;
END;
/
BEGIN
  DBMS_RLS.DROP_POLICY('HR_APP', 'ATTENDANCE', 'HR_ATTENDANCE_DEPT_VPD');
EXCEPTION
  WHEN OTHERS THEN
    IF SQLCODE != -28102 THEN RAISE; END IF;
END;
/
BEGIN
  DBMS_RLS.DROP_POLICY('HR_APP', 'LEAVE_REQUESTS', 'HR_LEAVE_DEPT_VPD');
EXCEPTION
  WHEN OTHERS THEN
    IF SQLCODE != -28102 THEN RAISE; END IF;
END;
/
